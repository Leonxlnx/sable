/**
 * The bridge reads what Claude Code writes in the person's place (shared/synthetic.ts) as the
 * window does: chat titles in plain words (also old chats titled with tags), the handover summary,
 * the turn a check reads, the turn Before / after belongs to.
 */
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import type { TimelineItem } from '@shared/protocol';
import { DELEGATE_REPORT, delegateReport, HANDOVER_HEAD_ACCOUNT, HANDOVER_TAIL, HANDOVER_JOIN, STEER_NOW_BLOCK, userItemText } from '@shared/synthetic';
import { chatMarkdown } from '../server/core/chat-markdown';
import { saidOf } from '../server/services/search';
import { handoverText } from '../server/accounts/handover';
import { App } from '../server/app';
import { turnSlice } from '../server/core/check';
import { autoTitle } from '../server/core/runtime';
import { DemoProvider } from '../server/providers/demo';
import { leadOf } from '../server/services/capture';

const NOTE = '<task-notification>\n<task-id>b296xlpn0</task-id>\n<status>completed</status>\n<summary>Background command "Build the installer" completed (exit code 0)</summary>\n</task-notification>';
const MODEL = '<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>';
const OUT = '<local-command-stdout>Set model to Opus 5.5</local-command-stdout>';
const CAVEAT = '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>';

let n = 0;
const at = () => ++n;
const user = (id: string, text: string): TimelineItem => ({ id, ts: at(), type: 'user', text, state: 'sent' });
const text = (id: string, t: string): TimelineItem => ({ id, ts: at(), type: 'text', text: t, streaming: false });
const tool = (id: string): TimelineItem => ({ id, ts: at(), type: 'tool', name: 'Edit', kind: 'edit', title: 'Edit a.ts', status: 'done', detail: { path: 'a.ts' } });
const turn = (id: string): TimelineItem => ({ id, ts: at(), type: 'turn', durationMs: 1 });

it('omits a hidden delegate report from export and search', () => {
  const items = [user('u', 'Review the changes'), user('hidden', DELEGATE_REPORT + '\n\n' + delegateReport('Review', 'failed', 'Private child report')), text('t', 'I found the cause')];
  expect(saidOf(items).map(i => i.id)).toEqual(['u', 't']);
  const md = chatMarkdown({ title: 'Review', provider: 'claude', cwd: '.', createdAt: 1 }, items);
  expect(md).toContain('Review the changes');
  expect(md).not.toContain('Private child report');
  expect(md).not.toContain(DELEGATE_REPORT);
});

it('keeps personal quotations and hides the handover report in transcript, export and search', () => {
  const handover = HANDOVER_HEAD_ACCOUNT + '\nAgent: Done\n' + HANDOVER_TAIL + HANDOVER_JOIN;
  const hidden = user('hidden', handover + DELEGATE_REPORT + '\n\n' + delegateReport('Review', 'done', 'Child finished'));
  expect(saidOf([hidden])).toEqual([]);
  for (const words of [STEER_NOW_BLOCK, 'before ' + STEER_NOW_BLOCK + ' after', 'words <system-reminder>unfinished']) {
    const card = { ...user('quote', words), authored: true } as TimelineItem;
    expect(userItemText(card)).toBe(words);
    expect(saidOf([card])).toMatchObject([{ text: words }]);
    const md = chatMarkdown({ title: 'Review', provider: 'claude', cwd: '.', createdAt: 1 }, [hidden, card]);
    expect(md).toContain(words);
    expect(md).not.toContain(DELEGATE_REPORT);
  }
});

describe('titles', () => {
  it('titles a chat that opens with one of these in plain words', () => {
    expect(autoTitle(NOTE)).toBe('Background task finished: Build the installer');
    expect(autoTitle(MODEL)).toBe('/model opus');
    expect(autoTitle(CAVEAT)).toBe('New session');
    expect(autoTitle('Fix the login bug\n<system-reminder>x</system-reminder>')).toBe('Fix the login bug');
    expect(autoTitle('Fix the login bug')).toBe('Fix the login bug');
  });

  const homes: string[] = [];
  const apps: App[] = [];
  afterEach(async () => {
    for (const app of apps.splice(0)) await app.dispose();
    for (const home of homes.splice(0)) rmSync(home, { recursive: true, force: true });
  });
  const start = (home: string) => {
    const app = new App({ home, providers: [(ctx) => new DemoProvider(ctx, { speed: 0 })], quiet: true });
    apps.push(app);
    return app;
  };

  it('gives an old chat titled with tags its plain words when Sable starts, and leaves names people gave alone', async () => {
    const home = mkdtempSync(path.join(tmpdir(), 'sable-synth-'));
    homes.push(home);
    let app = start(home);
    const a = (await app.call('session.create', { provider: 'demo', cwd: home })).session.id;
    const b = (await app.call('session.create', { provider: 'demo', cwd: home })).session.id;
    const c = (await app.call('session.create', { provider: 'demo', cwd: home, title: '<task-notification>' })).session.id;
    const d = (await app.call('session.create', { provider: 'demo', cwd: home })).session.id;
    app.sessions.get(a)!.update({ title: '<task-notification>' });
    app.sessions.get(b)!.update({ title: '[Request interrupted by user]' });
    app.sessions.get(d)!.update({ title: 'Refactor the session store' });
    await app.dispose();
    apps.splice(0);
    app = start(home);
    expect(app.sessions.get(a)!.meta.title).toBe('Background task');
    expect(app.sessions.get(b)!.meta.title).toBe('New session');
    expect(app.sessions.get(c)!.meta.title).toBe('<task-notification>');
    expect(app.sessions.get(d)!.meta.title).toBe('Refactor the session store');
  });
});

describe('the handover summary', () => {
  it('says them in plain words and leaves the wrappers out', () => {
    const out = handoverText([user('1', 'Build the installer in the background'), text('2', 'Started.'), user('3', NOTE), text('4', 'It built.'), user('5', CAVEAT), user('6', MODEL), user('7', OUT)]);
    expect(out).toContain('User: Build the installer in the background');
    expect(out).toContain('Event: Background task finished: Build the installer');
    expect(out).toContain('User ran: /model opus');
    expect(out).toContain('Output: Set model to Opus 5.5');
    expect(out).not.toContain('<');
    expect(out).not.toContain('Caveat');
  });
});

describe('the turn a check reads', () => {
  it('takes a notification the agent took mid-turn as part of the turn, as the window shows it', () => {
    const items = [user('u1', 'Refactor it'), tool('w1'), user('n1', NOTE), tool('w2'), text('t1', 'Done.'), turn('T1')];
    const slice = turnSlice(items, 'u1')!;
    expect(slice.asks.map((a) => a.id)).toEqual(['u1', 'n1']);
    expect(slice.roots.map((r) => r.id)).toEqual(['w1', 'w2', 't1', 'T1']);
    expect(slice.ended).toBe(true);
  });

  it("keeps a command's output in the command's turn", () => {
    const slice = turnSlice([user('c1', MODEL), user('o1', OUT), turn('T1')], 'c1')!;
    expect(slice.asks.map((a) => a.id)).toEqual(['c1']);
    expect(slice.ended).toBe(true);
  });
});

describe('the turn Before / after belongs to', () => {
  it('is the one the window shows', () => {
    // A notification between turns opens one.
    expect(leadOf([user('u1', 'a'), text('t1', 'x'), turn('T1'), user('n1', NOTE), tool('w1'), turn('T2')])).toBe('n1');
    // Taken mid-turn, it joins the turn.
    expect(leadOf([user('u1', 'a'), tool('w1'), user('n1', NOTE), tool('w2')])).toBe('u1');
    // A command's output or a caveat opens nothing; the command does.
    expect(leadOf([user('u1', 'a'), turn('T1'), user('o1', OUT)])).toBe('u1');
    expect(leadOf([user('u1', 'a'), turn('T1'), user('c0', CAVEAT), user('c1', MODEL), user('o1', OUT)])).toBe('c1');
  });
});

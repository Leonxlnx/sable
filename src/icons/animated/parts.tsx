/**
 * The animated icon set: Phosphor icons redrawn as parts on Phosphor's own 256 grid (16 unit
 * stroke, round caps and joins; 24 for the bold ones), so that at rest each one matches the
 * original it replaces, pixel for pixel or within antialiasing. Where an original already keeps a
 * part in its own subpath, that subpath is used as is (a filled `F` part). Every part carries a
 * class; `animated.css` moves the parts when the control holding the icon is hovered or focused.
 *
 * Keys are icon names (`IconName`); `<Icon>` picks a definition here by name.
 */
export interface AnimatedDef {
  /** Stroke width on the 256 grid: 16 for regular, 24 for bold. */
  w?: 16 | 24;
  parts: ReactNode;
}

/** A filled part: a subpath taken from the Phosphor original. */
const F = ({ c, d }: { c?: string; d: string }) => <path className={c} d={d} fill="currentColor" stroke="none" />;
/** A line that can draw itself: normalised length so `stroke-dasharray: 1 2` and an offset of 1 hide it. */
const D = ({ c, d, dash }: { c: string; d: string; dash?: number }) => <path className={c} d={d} pathLength={1} strokeDasharray={dash === undefined ? undefined : `${dash} 2`} />;

/** Circles and rectangles as paths: Chrome draws <circle> and <rect> through its own fast paths, which
 * antialias differently from the filled outlines Phosphor ships, so the drawing would not match at rest. */
const circ = (cx: number, cy: number, r: number) => `M${cx - r},${cy}a${r},${r},0,1,0,${2 * r},0a${r},${r},0,1,0,${-2 * r},0Z`;
const rrect = (x: number, y: number, w: number, h: number, r: number) =>
  r
    ? `M${x + r},${y}H${x + w - r}a${r},${r},0,0,1,${r},${r}V${y + h - r}a${r},${r},0,0,1,${-r},${r}H${x + r}a${r},${r},0,0,1,${-r},${-r}V${y + r}a${r},${r},0,0,1,${r},${-r}Z`
    : `M${x},${y}H${x + w}V${y + h}H${x}Z`;


/**
 * Messages an agent's own harness writes in the person's place. Claude Code puts some of its own
 * doings into the conversation as user messages: a background task or a sub-agent that finished
 * (`<task-notification>`), a slash command (`<command-name>/model</command-name>…`) and what it
 * printed (`<local-command-stdout>`), a `!` shell command and its output, a message from another
 * session or a teammate, the summary that continues a compacted conversation, and wrappers the
 * person never needs to read (`<system-reminder>`, `<local-command-caveat>`, interrupt markers).
 *
 * One parser for all of them, so the bridge, the desktop and the phone read them alike (the phone
 * imports this file through its `@shared` alias). It knows the shapes, tolerates odd whitespace,
 * attributes, a missing closing tag (a message cut short) and text around the blocks; anything it
 * does not recognise is a person's message and stays one (`parseSynthetic` gives null).
 * Pure: no imports, no node or DOM.
 */

export type TaskKind = 'command' | 'agent' | 'monitor' | 'task';
/** How a task ended, read from its status, its exit code and its summary. */
export type TaskOutcome = 'done' | 'failed' | 'stopped' | 'running' | 'unknown';

/** A background task's notification: a shell command, a sub-agent, a monitor. */
export interface TaskNote {
  id?: string;
  toolUseId?: string;
  kind: TaskKind;
  /** The status as written (`completed`, `failed`, `killed`, ...), lower case; '' when absent. */
  status: string;
  outcome: TaskOutcome;
  /** The harness's own line: `Background command "Build the installer" completed (exit code 0)`. */
  summary: string;
  /** The task's name: the quoted part of the summary (`Build the installer`), else ''. */
  name: string;
  exitCode?: number;
  /** What a sub-agent reported (markdown). */
  result?: string;
  outputFile?: string;
  usage?: { tokens?: number; toolUses?: number; durationMs?: number };
}

export type SyntheticPart =
  | { kind: 'task'; task: TaskNote }
  /** A slash command: `name` with its slash (`/model`), `args` as typed (`opus`). */
  | { kind: 'command'; name: string; args: string }
  /** A `!` shell command typed in the agent's own terminal. */
  | { kind: 'bash'; command: string }
  /** What a local command or a `!` command printed. */
  | { kind: 'output'; text: string; error: boolean; source: 'command' | 'bash'; exitCode?: number }
  /** A message from elsewhere: another session, a teammate, a channel. */
  | { kind: 'message'; from: string; text: string }
  /** The summary a compacted conversation continues from. */
  | { kind: 'summary'; text: string }
  /** Nothing the person needs to read (reminders, caveats, interrupt markers, hook output). */
  | { kind: 'hidden'; tag: string; text: string };

/**
 * What the message is in the conversation:
 * - `notification`: something happened outside the turn (a task finished, a message came in); the
 *   agent takes it up, so it opens a turn (or a segment of the running one);
 * - `command`: a slash or `!` command the person ran; it opens a turn like a message does;
 * - `output`: what a command printed; part of the command's turn;
 * - `summary`: a compacted conversation's summary; part of the turn it came in;
 * - `hidden`: nothing to show.
 */
export type SyntheticRole = 'notification' | 'command' | 'output' | 'summary' | 'hidden';

export interface Synthetic {
  role: SyntheticRole;
  parts: SyntheticPart[];
  /** Text outside the recognised blocks (a model-directed trailer such as "Read the output file..."). */
  extra?: string;
}

// ───────────────────────────────── the tags ─────────────────────────────────

const COMMAND_TAGS = new Set(['command-name', 'command-message', 'command-args', 'command-contents']);
const OUTPUT_TAGS = new Set(['local-command-stdout', 'local-command-stderr', 'bash-stdout', 'bash-stderr']);
const HIDDEN_TAGS = new Set(['local-command-caveat', 'system-reminder', 'system_reminder', 'user-prompt-submit-hook', 'tick', 'total_tokens', 'bash-exit-code']);
const MESSAGE_TAGS = new Set(['teammate-message', 'cross-session-message', 'channel', 'agent-message', 'coordinator-relay', 'slack-ping', 'slack-tag-message']);
const KNOWN = new Set(['task-notification', 'bash-input', ...COMMAND_TAGS, ...OUTPUT_TAGS, ...HIDDEN_TAGS, ...MESSAGE_TAGS]);
/** Wrappers that can sit inside a person's own message: stripped from what is shown of it. */
const STRIP_TAGS = ['system-reminder', 'system_reminder', 'local-command-caveat', 'user-prompt-submit-hook'];

/** The harness's bracketed markers (an interrupt, a call cut short). */
const MARKER = /^\[(?:Request interrupted|Agent call interrupted|Tool call did not complete)[^\]\n]*\]?/;
const CAVEAT = /^Caveat: The messages below were generated by the user while running local commands\b[^\n]*/;
const CONTINUED = /^This session is being continued from a previous conversation\b/;
const OPEN_TAG = /<([a-zA-Z][\w-]*)((?:\s[^<>]*?)?)(\/?)>/y;
// eslint-disable-next-line no-control-regex
const ANSI = /\u001b\[[0-9;?]*[ -/]*[@-~]/g;
const OUTPUT_TRAILER = /Read the output file to retrieve the result:\s*(\S[^\n]*)/i;

interface Block {
  tag: string;
  attrs: Record<string, string>;
  body: string;
}

function attrsOf(raw: string): Record<string, string> {
  const out: Record<string, string> = {};
  const re = /([\w-]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+))/g;
  for (let m = re.exec(raw); m; m = re.exec(raw)) out[m[1]] = m[2] ?? m[3] ?? m[4] ?? '';
  return out;
}

/** Whether a known block opens at `i`: its tag, attributes and where its body starts. */
function openAt(text: string, i: number): { tag: string; attrs: Record<string, string>; start: number; self: boolean } | null {
  if (text.charCodeAt(i) !== 60 /* < */) return null;
  OPEN_TAG.lastIndex = i;
  const m = OPEN_TAG.exec(text);
  if (!m || !KNOWN.has(m[1])) return null;
  return { tag: m[1], attrs: attrsOf(m[2] ?? ''), start: i + m[0].length, self: m[3] === '/' };
}

/** The message's known blocks in order, and the text around them. Null when it holds none. */
function scan(text: string): { blocks: Block[]; free: string } | null {
  const blocks: Block[] = [];
  let free = '';
  let i = 0;
  const n = text.length;
  while (i < n) {
    const open = openAt(text, i);
    if (open) {
      if (open.self) {
        blocks.push({ tag: open.tag, attrs: open.attrs, body: '' });
        i = open.start;
        continue;
      }
      const end = `</${open.tag}>`;
      // A sub-agent's result is free text and may mention the closing tag: the block runs to its last one.
      const close = open.tag === 'task-notification' ? lastClose(text, end, open.start) : text.indexOf(end, open.start);
      // No closing tag: the message was cut short and the block runs to its end, when what follows
      // reads like its inside (else it is the person's own words that start with a tag).
      if (close >= 0 || cutBlock(open.tag, text.slice(open.start))) {
        blocks.push({ tag: open.tag, attrs: open.attrs, body: close < 0 ? text.slice(open.start) : text.slice(open.start, close) });
        i = close < 0 ? n : close + end.length;
        continue;
      }
    }
    const rest = i === 0 || /\s/.test(text[i - 1] ?? '') ? text.slice(i, i + 200) : '';
    const marker = rest && (MARKER.exec(rest) ?? CAVEAT.exec(rest));
    if (marker) {
      blocks.push({ tag: marker[0].startsWith('[') ? 'marker' : 'caveat', attrs: {}, body: marker[0] });
      i += marker[0].length;
      continue;
    }
    // Free text up to the next known block.
    let j = text.indexOf('<', i + 1);
    while (j >= 0 && !openAt(text, j)) j = text.indexOf('<', j + 1);
    if (j < 0) j = n;
    free += text.slice(i, j);
    i = j;
  }
  return blocks.length ? { blocks, free } : null;
}

const TASK_CHILD = /<(task-id|task_id|tool-use-id|output-file|status|summary|task-type|result|usage)\b/;

/** Whether an unclosed block is one cut short: nothing after it, or (a notification, a command) its inside. */
function cutBlock(tag: string, rest: string): boolean {
  if (!rest.trim()) return true;
  if (tag === 'task-notification') return TASK_CHILD.test(rest);
  return COMMAND_TAGS.has(tag) || OUTPUT_TAGS.has(tag) || tag === 'bash-input';
}

/** The last `end` after `from` that is followed only by whitespace or free text (not inside the result). */
function lastClose(text: string, end: string, from: number): number {
  const first = text.indexOf(end, from);
  if (first < 0) return -1;
  // Several notifications in one message: each closes at its own first closing tag when another opens after it.
  const next = text.indexOf('<task-notification', first);
  const last = text.lastIndexOf(end, next < 0 ? text.length : next);
  return last >= first ? last : first;
}

const clean = (s: string) => s.replace(/\r\n?/g, '\n').replace(ANSI, '');

/** Claude's local /compact stdout, when a compact boundary already represents it. */
export function isCompactOutput(text: string, bare = false): boolean {
  const trimmed = clean(text).trim();
  const stdout = /^<local-command-stdout>([^<>]*)<\/local-command-stdout>$/.exec(trimmed);
  const value = stdout ? stdout[1].trim() : bare ? trimmed : '';
  return /^Compacted(?:\s*\([\w+ -]+ to see full summary\))?(?:\s+Tip: [^\n<>]+)?$/.test(value);
}

/** A child element's text (`<status>completed</status>`): to its closing tag, or to the end when it is cut. */
function child(body: string, name: string, last = false): string | undefined {
  const open = new RegExp(`<${name}(?:\\s[^<>]*)?>`, 'i');
  const m = open.exec(body);
  if (!m) return undefined;
  const start = m.index + m[0].length;
  const end = `</${name}>`;
  const close = last ? body.toLowerCase().lastIndexOf(end) : body.toLowerCase().indexOf(end, start);
  return (close >= start ? body.slice(start, close) : body.slice(start)).trim();
}

const num = (s: string | undefined) => {
  if (s == null || !/^-?\d+$/.test(s.trim())) return undefined;
  return Number(s.trim());
};

function outcomeOf(status: string, exitCode: number | undefined, summary: string): TaskOutcome {
  if (status === 'failed' || status === 'error' || (exitCode != null && exitCode !== 0)) return 'failed';
  if (status === 'killed' || status === 'stopped' || status === 'cancelled' || status === 'canceled') return 'stopped';
  if (status === 'running' || status === 'pending' || status === 'progress') return 'running';
  if (status === 'completed' || status === 'complete' || status === 'done' || status === 'success' || status === 'succeeded' || status === 'finished') return 'done';
  if (/\bfailed\b/i.test(summary)) return 'failed';
  if (/\b(was stopped|stopped|killed|cancell?ed)\b/i.test(summary)) return 'stopped';
  if (/\b(completed?|finished|done)\b/i.test(summary)) return 'done';
  return 'unknown';
}

function kindOf(type: string, summary: string, agentish: boolean): TaskKind {
  const t = type.toLowerCase();
  if (/agent/.test(t)) return 'agent';
  if (/monitor/.test(t)) return 'monitor';
  if (/bash|shell|command/.test(t)) return 'command';
  if (/^\s*background command\b/i.test(summary)) return 'command';
  if (/^\s*(sub-?)?agent\b/i.test(summary) || agentish) return 'agent';
  if (/^\s*monitor\b/i.test(summary)) return 'monitor';
  return 'task';
}

function usageOf(body: string | undefined): TaskNote['usage'] {
  if (!body) return undefined;
  const out: NonNullable<TaskNote['usage']> = {};
  const re = /(total[_-]?tokens|tool[_-]?uses|duration[_-]?ms)\s*(?::|=|>)\s*(\d+)/gi;
  for (let m = re.exec(body); m; m = re.exec(body)) {
    const key = m[1].toLowerCase().replace(/[_-]/g, '');
    const v = Number(m[2]);
    if (key === 'totaltokens') out.tokens = v;
    else if (key === 'tooluses') out.toolUses = v;
    else out.durationMs = v;
  }
  return Object.keys(out).length ? out : undefined;
}

function taskOf(body: string): TaskNote {
  const summary = clean(child(body, 'summary') ?? '').replace(/\s+/g, ' ').trim();
  const status = (child(body, 'status') ?? '').toLowerCase().trim();
  const result = child(body, 'result', true);
  const usage = usageOf(child(body, 'usage'));
  const exitCode = num(child(body, 'exit-code') ?? child(body, 'exit_code')) ?? num(/exit code (-?\d+)/i.exec(summary)?.[1]);
  const name = /["“]([^"”]+)["”]/.exec(summary)?.[1].trim() ?? '';
  const task: TaskNote = {
    kind: kindOf(child(body, 'task-type') ?? child(body, 'task_type') ?? '', summary, result != null || !!usage),
    status,
    outcome: outcomeOf(status, exitCode, summary),
    summary,
    name,
  };
  const id = child(body, 'task-id') ?? child(body, 'task_id');
  const toolUseId = child(body, 'tool-use-id') ?? child(body, 'tool_use_id');
  const outputFile = child(body, 'output-file') ?? child(body, 'output_file');
  if (id) task.id = id;
  if (toolUseId) task.toolUseId = toolUseId;
  if (exitCode != null) task.exitCode = exitCode;
  if (result) task.result = clean(result).trim();
  if (outputFile) task.outputFile = outputFile.trim();
  if (usage) task.usage = usage;
  return task;
}

function slashName(name: string): string {
  const n = name.trim().split(/\s+/)[0] ?? '';
  return !n ? '' : n.startsWith('/') ? n : `/${n}`;
}

/** The message's parts, or null when it is a person's message (nothing recognised, or their own words around a wrapper). */
export function parseSynthetic(text: string): Synthetic | null {
  if (typeof text !== 'string' || !maybeSynthetic(text)) return null;
  const src = text.replace(/\r\n?/g, '\n');
  const lead = src.trimStart();
  if (CONTINUED.test(lead)) return { role: 'summary', parts: [{ kind: 'summary', text: lead.trim() }] };
  // Sable's own words sent in the person's place (a turn carried on after a limit, an /until round),
  // read back from an agent's transcript: nothing of the person's to show.
  const own = sableMessage(lead);
  if (own) return { role: 'hidden', parts: [{ kind: 'hidden', tag: 'sable', text: own }] };
  const found = scan(src);
  if (!found) return null;
  const parts: SyntheticPart[] = [];
  let command: { name: string; args: string; message: string } | null = null;
  let lastBash: Extract<SyntheticPart, { kind: 'output' }> | null = null;
  for (const b of found.blocks) {
    if (b.tag === 'task-notification') parts.push({ kind: 'task', task: taskOf(b.body) });
    else if (COMMAND_TAGS.has(b.tag)) {
      if (!command) {
        command = { name: '', args: '', message: '' };
        parts.push({ kind: 'command', name: '', args: '' });
      }
      const v = clean(b.body).trim();
      if (b.tag === 'command-name') command.name = v;
      else if (b.tag === 'command-args') command.args = v;
      else if (b.tag === 'command-message') command.message = v;
    } else if (b.tag === 'bash-input') parts.push({ kind: 'bash', command: clean(b.body).trim() });
    else if (OUTPUT_TAGS.has(b.tag)) {
      const out = clean(b.body).replace(/^\n+|\s+$/g, '');
      if (!out.trim()) {
        parts.push({ kind: 'hidden', tag: b.tag, text: '' });
        continue;
      }
      const part = { kind: 'output' as const, text: out, error: b.tag.endsWith('stderr'), source: b.tag.startsWith('bash') ? ('bash' as const) : ('command' as const) };
      parts.push(part);
      if (part.source === 'bash') lastBash = part;
    } else if (MESSAGE_TAGS.has(b.tag)) {
      const a = b.attrs;
      const from = (a.teammate_id ?? a.from ?? a.name ?? a.source ?? a.sender ?? '').trim();
      parts.push({ kind: 'message', from, text: clean(b.body).trim() });
    } else {
      if (b.tag === 'bash-exit-code' && lastBash) {
        const code = num(clean(b.body));
        if (code != null) lastBash.exitCode = code;
      }
      parts.push({ kind: 'hidden', tag: b.tag, text: clean(b.body).trim() });
    }
  }
  if (command) {
    const at = parts.findIndex((p) => p.kind === 'command');
    const c = command;
    // The name as typed (`/model`); older lines carry only the message ("model", "review is running…").
    const name = slashName(c.name) || slashName(c.message.replace(/\s+is running.*$/i, ''));
    if (name) parts[at] = { kind: 'command', name, args: c.args };
    else parts.splice(at, 1, { kind: 'hidden', tag: 'command', text: c.message });
  }
  const free = clean(found.free).trim();
  const has = (k: SyntheticPart['kind']) => parts.some((p) => p.kind === k);
  const role: SyntheticRole = has('task') || has('message') ? 'notification' : has('command') || has('bash') ? 'command' : has('output') ? 'output' : 'hidden';
  // Only wrappers around words of the person's own: their message, shown without the wrappers (`userText`).
  if (role === 'hidden' && free) return null;
  const out: Synthetic = { role, parts };
  if (free) {
    out.extra = free;
    const file = OUTPUT_TRAILER.exec(free)?.[1]?.trim();
    if (file) for (const p of parts) if (p.kind === 'task' && !p.task.outputFile) p.task.outputFile = file;
  }
  return out;
}

/** A cheap first look: could this text be one of these messages at all? */
export function maybeSynthetic(text: string): boolean {
  let i = 0;
  while (i < text.length && (text.charCodeAt(i) <= 32 || text.charCodeAt(i) === 0xfeff)) i++;
  const c = text[i];
  if (c === '<' || c === '[') return true;
  return text.startsWith('Caveat:', i) || text.startsWith('This session is being continued', i) || SABLE_OPENERS.some((o) => text.startsWith(o, i));
}

const cache = new WeakMap<object, Synthetic | null>();

/** `parseSynthetic` of a user item's text, read once per item object (items are replaced, never changed). */
export function syntheticOf(item: { type: string; text?: string } | undefined | null): Synthetic | null {
  if (!item || item.type !== 'user' || typeof item.text !== 'string') return null;
  if (!maybeSynthetic(item.text)) return null;
  let s = cache.get(item);
  if (s === undefined) {
    s = parseSynthetic(item.text);
    cache.set(item, s);
  }
  return s;
}

/**
 * Whether the message only belongs to the turn around it (what a command printed, a summary, a
 * reminder) and never opens one of its own: no person's words, nothing that starts work.
 */
export function partOfTurn(s: Synthetic | null | undefined): boolean {
  return !!s && (s.role === 'output' || s.role === 'summary' || s.role === 'hidden');
}


/** "Background task finished", "Agent failed", "Background task stopped". */
export function taskLabel(t: TaskNote): string {
  const who = t.kind === 'agent' ? 'Agent' : t.kind === 'monitor' ? 'Monitor' : 'Background task';
  switch (t.outcome) {
    case 'done':
      return `${who} finished`;
    case 'failed':
      return `${who} failed`;
    case 'stopped':
      return `${who} stopped`;
    case 'running':
      return t.kind === 'monitor' ? 'Monitor event' : `${who} running`;
    default:
      return who;
  }
}

/** What the task was: its quoted name, else its summary, else ''. */
export function taskName(t: TaskNote): string {
  return t.name || t.summary;
}

const firstLine = (s: string) =>
  s
    .split('\n')
    .map((l) => l.trim())
    .find(Boolean) ?? '';

/** One part as a plain line: "Background task finished: Build the installer", "/model opus". */
export function partLine(p: SyntheticPart): string {
  switch (p.kind) {
    case 'task': {
      const name = taskName(p.task);
      return name ? `${taskLabel(p.task)}: ${name}` : taskLabel(p.task);
    }
    case 'command':
      return p.args ? `${p.name} ${p.args}` : p.name;
    case 'bash':
      return `! ${p.command}`;
    case 'output':
      return firstLine(p.text);
    case 'message': {
      const said = firstLine(p.text);
      return `Message from ${p.from || 'another session'}${said ? `: ${said}` : ''}`;
    }
    case 'summary':
      return 'Conversation summary';
    default:
      return '';
  }
}

/** The whole message as one plain line ('' for one with nothing to show). */
export function syntheticLine(s: Synthetic): string {
  const shown = s.parts.filter((p) => p.kind !== 'hidden');
  if (!shown.length) return '';
  const tasks = shown.filter((p) => p.kind === 'task');
  if (tasks.length > 1) return `${partLine(tasks[0])} and ${tasks.length - 1} more`;
  return partLine(tasks[0] ?? shown[0]);
}

// ───────────────────────── what Sable itself writes ─────────────────────────
//
// Every text Sable gives an agent with or as a message, known here so no reader shows it as the
// person's: the agents keep it in their transcripts, and a conversation read back from there (after
// a restart, a move, a switch) would otherwise show it in the person's bubble.
// - `STEER_FIRST_BLOCK`, the note after a move (`moveNote`), the compaction opener: `<system-reminder>`
//   blocks, stripped above.
// - The handover before the person's words after a switch of agent or a move without the
//   conversation (`handoverText`): a head, the exchanges, `HANDOVER_TAIL`, then `HANDOVER_JOIN`.
// - A turn carried on after a limit (`RESUME_*`): the whole message, or a trailer after the
//   person's words.
// - An `/until` round's failure (`server/core/until.ts` `failureMessage`): the whole message.
// - The Browser tab's line after the person's words (`server/providers/browser-tool.ts`).

/** Claude Code's own stand-in for an answer: written when a conversation is resumed after a turn was cut, and as a refused request's words at some limits. Never the agent's answer. */
export const STAND_IN_ANSWER = 'No response requested.';

/** Whether a text is only Claude Code's stand-in answer (`STAND_IN_ANSWER`). */
export const isStandIn = (text: string | undefined | null): boolean => typeof text === 'string' && text.trim() === STAND_IN_ANSWER;

/**
 * Claude Code's own words for a request refused for the sign-in, which it writes as a synthetic
 * assistant message ("Failed to authenticate: OAuth session expired and could not be refreshed",
 * "Failed to refresh OAuth token: another Claude Code process is refreshing it…"). Never the agent's
 * answer: the chat says it once in its own notice (server/core/auth-gate.ts). Only ever applied to
 * messages the CLI marks as its own (`<synthetic>`), so an answer that quotes it stays.
 */
export const AUTH_FAILURE_TEXT = 'Failed to authenticate: OAuth session expired and could not be refreshed';
const AUTH_FAILURE = /^(?:Failed to authenticate\b|Failed to refresh OAuth token\b|OAuth (?:session|token) (?:has )?expired\b|Invalid API key\b|Not logged in\b|API Error: 401\b)/i;

/** Whether a text is Claude Code's own words for a request refused for the sign-in (`AUTH_FAILURE_TEXT` and its kin). */
export const isAuthFailure = (text: string | undefined | null): boolean => typeof text === 'string' && text.length < 1200 && AUTH_FAILURE.test(text.trim());

/**
 * A saved text that is only one of Claude Code's own sign-in failure lines, the whole of it and a
 * single short line: what chats saved before 0.2.20 hold as a text of the agent (since then the
 * provider never stores it). Far stricter than `isAuthFailure`, which is only asked about messages
 * the CLI marks as its own: here nothing says who wrote the text, so only the CLI's lines as it
 * writes them count (the expired session; a refresh that failed, said in one clause, or the line
 * about another process whatever follows on it; the 401 with the service's answer), each with or
 * without its "Please run /login". An answer that begins like one and then says more ("Failed to
 * refresh OAuth token: the staging client used the wrong credentials. I fixed its configuration.")
 * stays the agent's.
 */
const AUTH_FAILURE_LINE =
  /^(?:Failed to authenticate: OAuth session expired and could not be refreshed\.?|Failed to refresh OAuth token: another Claude Code process is refreshing it[^\n]{0,160}|Failed to refresh OAuth token: (?:[^.!?\n]|[.!?](?=\S)){1,200}[.!?…]?|Failed to authenticate\. API Error: 401(?: \{.*\})?)(?: · Please run \/login\.?)?$/;
export const isAuthFailureLine = (text: string | undefined | null): boolean => {
  if (typeof text !== 'string') return false;
  const t = text.trim();
  return t.length < 400 && !t.includes('\n') && AUTH_FAILURE_LINE.test(t);
};

/** A text nobody wrote: Claude Code's stand-in answer or its own sign-in failure line. Never shown as the agent's words. */
export const isNobodysWords = (text: string | undefined | null): boolean => isStandIn(text) || isAuthFailureLine(text);

/** The handover's heads: after a move to another account, a switch of agent, a return to an agent. */
